class MedicalRecord {
  final int id;
  final String title;
  final String type;
  final double moneySpent;
  final String date;
  final String details;

  MedicalRecord({
    required this.id,
    required this.title,
    required this.type,
    required this.moneySpent,
    required this.date,
    required this.details,
  });
}
